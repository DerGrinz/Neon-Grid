const ROT_NAMES = ['0', 'R', '2', 'L'];

export function getKicks(type: PieceType, fromRot: number, toRot: number): Kick[] {
  const key = `${ROT_NAMES[fromRot]}${ROT_NAMES[toRot]}`;
  if (type === 'I') return I_KICKS[key] ?? [[0, 0]];
  if (type === 'O') return [[0, 0]];
  return JLSTZ_KICKS[key] ?? [[0, 0]];
}

export function shuffleBag(): PieceType[] {
  const bag = [...ALL_PIECES];
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  return bag;
}
